#!/usr/bin/env bash
# Rebuilds lead-email.generated.js, the plain-JS bundle of the lead-drip emails
# that run-lead-drip.js requires. Run from the repo root after changing
# libraries/nestjs-libraries/src/emails/templates/lead-campaign.template.ts or
# libraries/nestjs-libraries/src/emails/layout/email.layout.ts, and commit the
# result: the server runs the drip with plain node, no TypeScript toolchain.
set -euo pipefail

cd "$(dirname "$0")/../.."

node_modules/.bin/esbuild \
  libraries/nestjs-libraries/src/emails/templates/lead-campaign.template.ts \
  --bundle --platform=node --format=cjs --target=node18 --legal-comments=none \
  --outfile=scripts/lead-campaign/lead-email.generated.js \
  "--banner:js=// GENERATED by scripts/lead-campaign/build-lead-email.sh - do not edit by hand.
// Source: libraries/nestjs-libraries/src/emails/templates/lead-campaign.template.ts"
